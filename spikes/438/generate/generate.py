"""Turns a draft contract into its Python SDK (docs/plans/hyalos-kernel-python, ADR-004 and ADR-005).

    python3 -I generate.py <contract file>        # the SDK on standard output

The output is a pure function of the contract's bytes: a fixed name table, a fixed layout, and
members emitted in the contract's own (ascending) order. Only the canonical byte form of a contract
is accepted, the same form the monitor's spike check accepts (`hyalos-os/audit/src/contract.rs`),
so no two byte forms give one SDK. Standard library only.
"""

import sys

MAX_CONTRACT = 4096

# The fixed name table: what each schema and effect kind the host supports is called in the SDK.
# A contract may grant only these.
SCHEMAS = {0: ("ask", "classify")}
KINDS = {0: ("notify", "team")}


def refuse(why):
    sys.stderr.write("refused: not a canonical contract: " + why + "\n")
    sys.exit(2)


def parse_list(data, at, supported):
    """The `[...]` list at `data[at:]` and the index after it, or a refusal."""
    if data[at:at + 1] != b"[":
        refuse("a list must open with [")
    at += 1
    values = []
    if data[at:at + 1] == b"]":
        return values, at + 1
    while True:
        end = at
        while end < len(data) and 0x30 <= data[end] <= 0x39:
            end += 1
        digits = data[at:end]
        if not digits or (len(digits) > 1 and digits[0] == 0x30) or len(digits) > 9:
            refuse("a value must be a decimal integer with no sign or leading zero")
        value = 0
        for c in digits:
            value = value * 10 + (c - 0x30)
        if value not in supported:
            refuse("value " + str(value) + " is not one the host supports")
        if values and values[-1] >= value:
            refuse("values must be distinct and ascending")
        values.append(value)
        sep = data[end:end + 1]
        if sep == b",":
            at = end + 1
        elif sep == b"]":
            return values, end + 1
        else:
            refuse("a list holds values separated by , and closes with ]")


def parse(data):
    """The contract's grants, `(asks, may_touch)`, from its canonical bytes."""
    if len(data) > MAX_CONTRACT:
        refuse("over 4096 bytes")
    head = b'{"asks":'
    if not data.startswith(head):
        refuse('it must begin {"asks":')
    asks, at = parse_list(data, len(head), SCHEMAS)
    middle = b',"may_touch":'
    if data[at:at + len(middle)] != middle:
        refuse('"may_touch" must follow "asks"')
    may_touch, at = parse_list(data, at + len(middle), KINDS)
    if data[at:] != b"}":
        refuse("nothing may follow the closing }")
    return asks, may_touch


PREAMBLE = '''\
# The hyalOS task SDK, generated by spikes/438/generate/generate.py from the contract
# {contract}
# Do not edit: regenerate it (spikes/438/README.md). Its one public name is `task`, and it holds
# only what the contract grants. The monitor, not this file, refuses anything else.

import _hyalos

_FIRST_DATA = 3
_LABELS = ("bug", "feature", "security", "other")
_NUMBER_MAX = 4294967295


def _bytes(value):
    if isinstance(value, str):
        return value.encode()
    if isinstance(value, (bytes, bytearray)):
        return bytes(value)
    raise TypeError("expected str or bytes")


def _number(text):
    if not text:
        return None
    n = 0
    for c in text:
        if c < 48 or c > 57:
            return None
        n = n * 10 + (c - 48)
    if n > _NUMBER_MAX:
        return None
    return n


class _Issue:
    def __init__(self, number, title):
        self.number = number
        self.title = title


def _issue(record):
    if not record:
        return _Issue(None, None)
    tab = record.find(b"\\t")
    if tab < 0:
        return _Issue(None, None)
    return _Issue(_number(record[:tab]), record[tab + 1:])
'''

ASK = """

class _Ask:
"""

ASK_METHOD = """\
    def {name}(self, text):
        label = _hyalos.infer({schema}, _bytes(text))
        if 0 <= label < len(_LABELS):
            return _LABELS[label]
        return "other"
"""

NOTIFY = """

class _Notify:
"""

NOTIFY_METHOD = """\
    def {name}(self, text):
        _hyalos.effect({kind}, _bytes(text))
"""

TASK = '''

class _Task:
    def read_inputs(self):
        issues = []
        index = _FIRST_DATA
        while True:
            record = _hyalos.read(index)
            if record is None:
                return issues
            issues.append(_issue(record))
            index += 1

    def finish(self, text):
        _hyalos.finish(_bytes(text))


task = _Task()
'''


def generate(data):
    asks, may_touch = parse(data)
    out = [PREAMBLE.format(contract=data.decode("ascii"))]
    if asks:
        out.append(ASK)
        for schema in asks:
            out.append(ASK_METHOD.format(name=SCHEMAS[schema][1], schema=schema))
    if may_touch:
        out.append(NOTIFY)
        for kind in may_touch:
            out.append(NOTIFY_METHOD.format(name=KINDS[kind][1], kind=kind))
    out.append(TASK)
    if asks:
        out.append("task.ask = _Ask()\n")
    if may_touch:
        out.append("task.notify = _Notify()\n")
    return "".join(out).encode("ascii")


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: generate.py <contract file>\n")
        sys.exit(2)
    with open(sys.argv[1], "rb") as f:
        data = f.read()
    sys.stdout.buffer.write(generate(data))


if __name__ == "__main__":
    main()
